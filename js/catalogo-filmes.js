function renderizarFilmes() {
  const pagina = window.location.pathname.split("/").pop();
  const filmes = filmesPorCategoria[pagina];
  const lista = document.querySelector("#lista-filmes");

  if (!filmes || !lista) return;

  lista.replaceChildren();

  filmes.forEach(({ titulo, imagem, alt, detalhes }) => {
    const coluna = document.createElement("div");
    coluna.className = "col-md-3 mb-4";

    const card = document.createElement("div");
    card.className = "card h-100 shadow-sm";

    const poster = document.createElement("img");
    poster.src = imagem;
    poster.className = "card-img-top";
    poster.alt = alt;

    const corpo = document.createElement("div");
    corpo.className = "card-body text-center";

    const tituloElemento = document.createElement("h6");
    tituloElemento.className = "card-title fw-bold";
    tituloElemento.textContent = titulo;

    const detalhesElemento = document.createElement("p");
    detalhesElemento.className = "card-text small text-muted";
    detalhesElemento.textContent = detalhes;

    corpo.append(tituloElemento, detalhesElemento);
    card.append(poster, corpo);
    coluna.append(card);
    lista.append(coluna);
  });
}

renderizarFilmes();
